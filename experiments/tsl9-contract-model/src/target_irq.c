/* Exact fixed-target BB18492..1849E. This small entry relies on original
   core/PFIC automatic context behavior; no generic interrupt ABI is assumed. */
__attribute__((naked,noreturn,used,section(".text.tsl9_ble_bb")))
void tsl9_ble_bb_irq(void){
 __asm__ volatile(
  ".option push\n"
  ".option norelax\n"
  ".option rvc\n"
  "lui a5,0x20000\n"
  "lw a5,4(a5)\n"
  "jalr a5\n"
  "mret\n"
  ".option pop\n"
 );
}
