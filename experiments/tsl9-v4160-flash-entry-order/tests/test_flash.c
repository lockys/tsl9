static void prefixes(void) {
    fixture baseline,f;fn_host h;unsigned n,flow,j;setup(&baseline,&h,0x08001055u,0x20005000u);
    CHECK(fn_run(&h,0x9c0au,word(baseline.destination),word(baseline.source))==FN_RETURNED);
    for(flow=1u;flow<=2u;flow++)for(n=1u;n<=baseline.count;n++) {
        setup(&f,&h,0x08001055u,0x20005000u);f.stop_at=n;f.stop_flow=(fn_flow)flow;cases++;
        CHECK(fn_run(&h,0x9c0au,word(f.destination),word(f.source))==(fn_flow)flow);
        CHECK(h.normal_register_outputs_valid==0u&&f.count==n&&h.operations==n);
        for(j=0;j<n;j++)CHECK(equal_request(&f.trace[j],&baseline.trace[j]));
    }
}
static void diagnostics(void) {
    uint32_t sites[]={0x18ee0u,0x18f02u,0x18f0cu,0x18f2au,0x18f44u};unsigned i,j;
    for(i=0;i<5u;i++)for(j=0;j<2u;j++) {
        fixture f;fn_host h;setup(&f,&h,0x08001000u,0x20005000u);cases++;
        if(j)f.unknown_site=sites[i];else f.busy_site=sites[i];
        CHECK(fn_run(&h,0x9c0au,word(f.destination),word(f.source))==FN_HALTED);
        CHECK(h.normal_register_outputs_valid==0u&&h.boundary==(j?FN_UNKNOWN_CONDITION:FN_HOST_POLL_BUDGET));
        CHECK(f.trace[f.count-1u].site==sites[i]);
        for(unsigned k=0;k<f.count;k++)CHECK(f.trace[k].kind!=FN_CSR_SET_REQUEST);
    }
    { fixture f;fn_host h;fn_word pointer;setup(&f,&h,0x08001000u,0x20005000u);pointer=word(f.source);pointer.known=0xffffff00u;cases++;
      CHECK(fn_run(&h,0x18ef2u,word(f.destination),pointer)==FN_HALTED&&h.boundary==FN_UNKNOWN_ADDRESS);CHECK(h.words_written==0u); }
    { fixture f;fn_host h;setup(&f,&h,0x080010ffu,0x20005000u);fn_word d=word(f.destination);d.known=0xffffff00u;cases++;
      CHECK(fn_run(&h,0x18ef2u,d,word(f.source))==FN_RETURNED);CHECK(equal_word(h.regs[10],word(0x08001000u))); }
}
