        if(i==4u)CHECK(f.count==201u&&h.regs[12].value==256u&&h.regs[13].value==0xfffeffffu&&h.regs[14].value==(f.last_ctrl.value&0xfffeffffu)&&h.regs[16].value==0x1020307fu);
        for(j=0;j<32u;j++)if(j!=1u&&j!=2u&&j!=10u&&j!=11u&&j!=13u&&j!=14u&&j!=15u&&!(i==4u&&(j==12u||j==16u)))CHECK(h.regs[j].value==0x90000000u+j);
