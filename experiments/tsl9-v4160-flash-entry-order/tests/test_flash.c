#define MAX_CELLS 4096u
#define MAX_TRACE 2048u
typedef struct { uint32_t address;fn_word word; } cell;
typedef struct {
    cell cells[MAX_CELLS];unsigned cells_count;
    fn_request trace[MAX_TRACE];unsigned count;
    unsigned stop_at;fn_flow stop_flow;
    uint32_t busy_site,unknown_site,unknown_data_site;
    uint32_t destination,source,alternative_source;
    unsigned mutate_source,overlap,mutate_frame,mutate_return,ctrl_reads;
    fn_word last_ctrl;
} fixture;
static unsigned long checks,cases;
#define CHECK(v) do { checks++;if(!(v)){fprintf(stderr,"failure line %u: %s\n",(unsigned)__LINE__,#v);exit(1);} } while(0)
static fn_word word(uint32_t v) { return fn_constant(v); }
static void put(fixture *f,uint32_t a,fn_word v) {
    unsigned i;for(i=0;i<f->cells_count;i++)if(f->cells[i].address==a){f->cells[i].word=v;return;}
    CHECK(f->cells_count<MAX_CELLS);f->cells[f->cells_count].address=a;f->cells[f->cells_count++].word=v;
}
static fn_word get(fixture *f,uint32_t a) {
    unsigned i;for(i=0;i<f->cells_count;i++)if(f->cells[i].address==a)return f->cells[i].word;
    return fn_failed();
}
static int equal_word(fn_word a,fn_word b) { return a.value==b.value&&a.known==b.known; }
static int equal_request(const fn_request *a,const fn_request *b) {
    return a->kind==b->kind&&a->site==b->site&&a->address==b->address&&a->value==b->value&&a->known==b->known&&a->width==b->width;
}
/* Independent expected external-effect order from the sealed ID2966 site ledger.
 * No expected trace is generated by calling an implementation under test. */
static void expect(fixture *f,unsigned *cursor,fn_kind kind,uint32_t site,uint32_t address,uint32_t value) {
    fn_request r;r.kind=kind;r.site=site;r.address=address;r.value=value;r.known=kind==FN_READ32_REQUEST?0u:UINT32_MAX;r.width=32u;
    CHECK(*cursor<f->count);CHECK(equal_request(&r,&f->trace[(*cursor)++]));
}
static uint32_t expect_ctrl(fixture *f,unsigned *cursor,unsigned *generation,uint32_t site) {
    expect(f,cursor,FN_READ32_REQUEST,site,0x40022010u,0u);
    return 0xa5000073u+(++*generation)*0x100u;
}
static void expect_unlock(fixture *f,unsigned *c) {
    expect(f,c,FN_WRITE32_REQUEST,0x18ea8u,0x40022004u,0x45670123u);
    expect(f,c,FN_WRITE32_REQUEST,0x18eaeu,0x40022004u,0xcdef89abu);
    expect(f,c,FN_WRITE32_REQUEST,0x18eb0u,0x40022024u,0x45670123u);
    expect(f,c,FN_WRITE32_REQUEST,0x18eb2u,0x40022024u,0xcdef89abu);
}
static void expect_lock(fixture *f,unsigned *c,unsigned *g) {
    uint32_t v=expect_ctrl(f,c,g,0x18ebau);expect(f,c,FN_WRITE32_REQUEST,0x18ec0u,0x40022010u,v|0x8000u);
}
static void expect_erase(fixture *f,unsigned *c,unsigned *g,uint32_t destination) {
    uint32_t v=expect_ctrl(f,c,g,0x18ec8u);expect(f,c,FN_WRITE32_REQUEST,0x18ed4u,0x40022010u,v|0x20000u);
    expect(f,c,FN_WRITE32_REQUEST,0x18ed6u,0x40022014u,destination&0xffffff00u);
    v=expect_ctrl(f,c,g,0x18ed8u);expect(f,c,FN_WRITE32_REQUEST,0x18edeu,0x40022010u,v|64u);
    expect(f,c,FN_READ32_REQUEST,0x18ee0u,0x4002200cu,0u);
    v=expect_ctrl(f,c,g,0x18ee6u);expect(f,c,FN_WRITE32_REQUEST,0x18eeeu,0x40022010u,v&0xfffdffffu);
}
static void expect_program(fixture *f,unsigned *c,unsigned *g,uint32_t destination,uint32_t source) {
    uint32_t v=expect_ctrl(f,c,g,0x18ef6u);unsigned i;expect(f,c,FN_WRITE32_REQUEST,0x18f00u,0x40022010u,v|0x10000u);
    expect(f,c,FN_READ32_REQUEST,0x18f02u,0x4002200cu,0u);expect(f,c,FN_READ32_REQUEST,0x18f0cu,0x4002200cu,0u);
    for(i=0;i<64u;i++) {
        expect(f,c,FN_READ32_REQUEST,0x18f1eu,source+4u*i,0u);
        expect(f,c,FN_WRITE32_REQUEST,0x18f26u,(destination&0xffffff00u)+4u*i,0x10203040u+i);
        expect(f,c,FN_READ32_REQUEST,0x18f2au,0x4002200cu,0u);
    }
    v=expect_ctrl(f,c,g,0x18f36u);expect(f,c,FN_WRITE32_REQUEST,0x18f3eu,0x40022010u,v|0x200000u);
    expect(f,c,FN_READ32_REQUEST,0x18f44u,0x4002200cu,0u);
    v=expect_ctrl(f,c,g,0x18f4au);expect(f,c,FN_WRITE32_REQUEST,0x18f52u,0x40022010u,v&0xfffeffffu);
}
static void oracle(fixture *f,uint32_t entry) {
    unsigned c=0,g=0;uint32_t sp=0x20007fe0u;
    if(entry==0x9c0au) {
        expect(f,&c,FN_WRITE32_REQUEST,0x9c0cu,sp+24u,0x90000008u);expect(f,&c,FN_WRITE32_REQUEST,0x9c0eu,sp+20u,0x90000009u);
        expect(f,&c,FN_WRITE32_REQUEST,0x9c10u,sp+28u,0x12345678u);expect(f,&c,FN_WRITE32_REQUEST,0x9c14u,sp+12u,f->source);
        expect(f,&c,FN_CSR_CLEAR_REQUEST,0x9c1au,0x800u,136u);expect_unlock(f,&c);
        expect(f,&c,FN_WRITE32_REQUEST,0x18e94u,0x4002200cu,49u);expect_erase(f,&c,&g,f->destination);
        expect(f,&c,FN_READ32_REQUEST,0x9c30u,sp+12u,0u);expect_program(f,&c,&g,f->destination,f->source);expect_lock(f,&c,&g);
        expect(f,&c,FN_CSR_SET_REQUEST,0x9c3cu,0x800u,136u);
        expect(f,&c,FN_READ32_REQUEST,0x9c40u,sp+28u,0u);expect(f,&c,FN_READ32_REQUEST,0x9c42u,sp+24u,0u);expect(f,&c,FN_READ32_REQUEST,0x9c44u,sp+20u,0u);
    } else if(entry==0x18e90u)expect(f,&c,FN_WRITE32_REQUEST,0x18e94u,0x4002200cu,f->destination);
    else if(entry==0x18e98u)expect_unlock(f,&c);
    else if(entry==0x18eb6u)expect_lock(f,&c,&g);
    else if(entry==0x18ec4u)expect_erase(f,&c,&g,f->destination);
    else if(entry==0x18ef2u)expect_program(f,&c,&g,f->destination,f->source);
    else CHECK(0);
    CHECK(c==f->count&&g==f->ctrl_reads);
}
static fn_flow provider(void *context,fn_host *h,const fn_request *r,fn_word *out) {
    fixture *f=(fixture *)context;CHECK(f->count<MAX_TRACE);f->trace[f->count++]=*r;CHECK(r->width==32u);
    if(r->kind==FN_READ32_REQUEST) {
        if(r->address==0x4002200cu) {
            *out=word(r->site==f->busy_site?3u:0u);
            if(r->site==f->unknown_site)out->known=0u;
            else out->known&=~0x80u; /* unrelated unknown bit must not block bits0/1 */
        } else if(r->address==0x40022010u) {
            *out=word(0xa5000000u+(++f->ctrl_reads)*0x100u+0x73u);f->last_ctrl=*out;
        } else *out=get(f,r->address);
        if(r->site==f->unknown_data_site)out->known=0xffff00ffu;
    } else if(r->kind==FN_WRITE32_REQUEST) {
        fn_word v={r->value,r->known};put(f,r->address,v);
        if(r->site==0x18f26u && r->address==(f->destination&0xffffff00u) && f->mutate_source)
            put(f,f->source+4u,word(0xdeadbeefu));
        if(r->site==0x18eeeu && f->mutate_frame)
            put(f,h->regs[2].value+12u,word(f->alternative_source));
        if(r->site==0x18ec0u && f->mutate_return) {
            put(f,h->regs[2].value+24u,word(0x31415926u));put(f,h->regs[2].value+20u,word(0x27182818u));
            if(f->mutate_return==2u)put(f,h->regs[2].value+28u,word(0x55556666u));
            if(f->mutate_return==3u)put(f,h->regs[2].value+28u,fn_failed());
        }
    } else CHECK(r->address==0x800u && r->value==136u && r->known==UINT32_MAX);
    if(f->stop_at && f->count==f->stop_at)return f->stop_flow;
    return FN_RETURNED;
}
static void setup(fixture *f,fn_host *h,uint32_t destination,uint32_t source) {
    unsigned i;memset(f,0,sizeof(*f));fn_host_init(h,provider,f);h->poll_budget=3u;
    for(i=0;i<32u;i++)h->regs[i]=word(0x90000000u+i);
    h->regs[2]=word(0x20008000u);h->regs[1]=word(0x12345678u);
    f->destination=destination;f->source=source;f->alternative_source=source+0x1000u;
    for(i=0;i<64u;i++) { put(f,source+4u*i,word(0x10203040u+i));put(f,f->alternative_source+4u*i,word(0x50607080u+i)); }
}
static void normal(void) {
    fixture f;fn_host h;unsigned i;uint32_t addresses[]={0x080010ffu,0x08077affu,0x200000ffu,0xffffff00u};
    for(i=0;i<sizeof(addresses)/sizeof(addresses[0]);i++) {
        unsigned j;setup(&f,&h,addresses[i],0x20005000u);cases++;
        CHECK(fn_run(&h,0x9c0au,word(f.destination),word(f.source))==FN_RETURNED);
        oracle(&f,0x9c0au);
        CHECK(h.normal_register_outputs_valid==1u&&h.words_written==64u&&f.count==226u);
        CHECK(h.regs[10].value==(f.destination&0xffffff00u));CHECK(h.regs[11].value==f.source);
        CHECK(h.regs[12].value==256u&&h.regs[13].value==0x8000u&&h.regs[14].value==0x40022000u);
        CHECK(h.regs[15].value==(f.last_ctrl.value|0x8000u));CHECK(h.regs[16].value==0x1020307fu);
        CHECK(h.regs[2].value==0x20008000u&&h.regs[1].value==0x12345678u);
        CHECK(h.regs[8].value==0x90000008u&&h.regs[9].value==0x90000009u);
        for(j=0;j<64u;j++)CHECK(get(&f,(f.destination&0xffffff00u)+j*4u).value==0x10203040u+j);
        for(j=0;j<32u;j++)if(j!=1u&&j!=2u&&j!=8u&&j!=9u&&!(j>=10u&&j<=16u))CHECK(h.regs[j].value==0x90000000u+j);
        CHECK(f.trace[4].kind==FN_CSR_CLEAR_REQUEST&&f.trace[f.count-4u].kind==FN_CSR_SET_REQUEST);
    }
}
