        oracle(&f,entries[i]);
        CHECK(h.regs[11].value==f.source&&h.regs[1].value==0x12345678u&&h.regs[2].value==0x20008000u);
        CHECK(h.regs[10].value==(i>=3u?(f.destination&0xffffff00u):f.destination));
